import assert from 'node:assert/strict';
import {PLANS,planCost,summarizePlan} from '../web/electricity-plans.js';
assert.equal(new Set(PLANS.map(p=>p.supplier)).size,8);
assert.equal(new Set(PLANS.map(p=>p.id)).size,PLANS.length);
const day={energy_kwh:100,day_kwh:60,night_kwh:40,distribution_cost_isk:1205,usage_cost_isk:2118.6,hs_orka:{supplier_cost_isk:730.8}};
const flat=PLANS.find(p=>p.id==='orkusalan-discount');
assert.equal(planCost(flat,day).supplier,982);
assert.equal(planCost(flat,day).total,2187);
assert.equal(planCost(PLANS.find(p=>p.id==='hs-night'),day).total,1935.8);
assert.equal(planCost(PLANS.find(p=>p.id==='straumlind-night'),day).total,2118.6);
assert.equal(planCost(flat,{...day,energy_kwh:null}),null);
assert.equal(planCost(flat,{...day,status:'reset'}),null);
assert.equal(planCost(PLANS.find(p=>p.id==='on-variable'),day),null);
assert.equal(planCost(PLANS.find(p=>p.id==='hs-night'),{...day,hs_orka:undefined}),null);
assert.equal(summarizePlan(flat,[day,day]).total,4374);
assert.equal(summarizePlan(flat,[]),null);
assert.equal(summarizePlan(flat,[day,{...day,energy_kwh:null}]),null);
assert.equal(planCost(PLANS.find(p=>p.id==='n1-discount'),day).supplier,998,'N1 points must not be treated as cash discounts');
console.log('Plan comparison: all eight suppliers, flat/night pricing, distribution, same-period sums, missing data and unsupported schedules passed.');
