import assert from 'node:assert/strict';
import {CounterHistory,buildSnapshot} from '../cloud/snapshot.js';
import {validateItem} from '../cloud/worker.js';
const row=(minutes,volume)=>({timestamp:new Date(Date.UTC(2026,10,8,0,minutes)).toISOString(),water_observed:true,hot_water_m3:volume,flow_m3h:.15,temp_supply_c:78,temp_return_c:28,voltages:[230,230,230],currents:[0,1,1]});
let h=new CounterHistory([row(0,100),row(10,101)]);
assert.equal(h.window(5,Date.parse(row(10,101).timestamp)/1000).volume_m3,.5);
assert.equal(h.window(5,Date.parse(row(10,101).timestamp)/1000).estimated,true);
assert.equal(h.window(10,Date.parse(row(10,101).timestamp)/1000).estimated,false);
assert.equal(h.window(15,Date.parse(row(10,101).timestamp)/1000).volume_m3,null);
h=new CounterHistory([row(0,100),row(1,90),row(2,101)]);
assert.equal(h.window(2,Date.parse(row(2,101).timestamp)/1000).status,'reset');
const s=buildSnapshot([row(0,100),row(1,101)],2,Date.UTC(2026,10,8,0,2));
assert.equal(s.summary.today_m3,1);assert.equal(s.summary.today_cost_isk,227.56);
assert.equal(s.water_usage.intervals[0].volume_m3,1);
assert.equal(s.health.connected,true);
assert.equal(buildSnapshot([],0).latest,null);
const item={source_id:'abc',collector_id:'unit-test',reading:row(0,100)};
assert.equal(validateItem(item).reading.hot_water_m3,100);
assert.throws(()=>validateItem({...item,reading:{...item.reading,hot_water_m3:NaN}}));
assert.throws(()=>validateItem({...item,reading:{...item.reading,voltages:[]}}));
console.log('Cloud calculations: gap estimates, resets, cost, missing history and validation passed.');
const electricRows=[{...row(0,100),elec_import_kwh:200,power_w:1000},{...row(60,101),elec_import_kwh:203,power_w:4000,phase_power_w:[0,3500,500],poll_interval_seconds:30,upload_interval_seconds:60}];
const electric=buildSnapshot(electricRows,2,Date.UTC(2026,10,8,1,1));
assert.equal(electric.electricity.daily[0].energy_kwh,3);
assert.equal(electric.electricity.daily[0].average_kw,3);
assert.equal(electric.electricity.peak_today_w,4000);
assert.equal(electric.latest.phase_power_w[1],3500);
assert.equal(electric.poll_interval_seconds,30);
assert.equal(electric.upload_interval_seconds,60);
assert.equal(electric.summary.today_m3,1);
assert.equal(electric.sensor_history['6h'].at(-1).power_kw,4);
assert.equal(electric.sensor_history['6h'].at(-1).segment_id,1);
const missing=buildSnapshot([{...row(0,100),water_observed:false,hot_water_m3:null,flow_m3h:null}],1);
assert.equal(missing.sensor_history['1h'][0].flow_lh,null);
const resetElectric=buildSnapshot([{...row(0,100),elec_import_kwh:200},{...row(1,101),elec_import_kwh:10}],2,Date.UTC(2026,10,8,0,2));
assert.equal(resetElectric.electricity.daily[0].energy_kwh,null);
assert.equal(resetElectric.electricity.daily[0].status,'reset');
const validated=validateItem({...item,reading:{...item.reading,phase_power_w:[0,3500,500],poll_interval_seconds:30,upload_interval_seconds:60}}).reading;
assert.deepEqual(validated.phase_power_w,[0,3500,500]);
assert.equal(validated.poll_interval_seconds,30);
assert.throws(()=>validateItem({...item,reading:{...item.reading,phase_power_w:[1,2]}}));
assert.throws(()=>validateItem({...item,reading:{...item.reading,poll_interval_seconds:0}}));
const mixed=new CounterHistory([{...row(0,100),poll_interval_seconds:60},{...row(1,100),poll_interval_seconds:30},{...row(2,101),poll_interval_seconds:30}]);
assert.equal(mixed.gaps().length,0);
console.log('Electricity usage, phase readings, observed peaks, cadence changes and missing sensor values verified.');
